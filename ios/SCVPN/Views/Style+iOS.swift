import SwiftUI

/// Метрики и шрифты экрана iOS — одно место на всё приложение.
///
/// **Источник истины — macOS:** `desktop/macOS/Sources/SCVPNApp/Views/Style.swift`.
/// Числа здесь обязаны совпадать с тамошними число в число: приложение должно
/// выглядеть одинаково на всех платформах, а расхождение в одном отступе видно
/// сразу, стоит положить телефон рядом с ноутбуком. Меняешь размер здесь —
/// меняй и там, иначе платформы разъедутся молча.
///
/// Цвета сюда не переезжают: они живут строками в `SCVPNCore.Palette` и оттуда
/// же сверяются с `android/.../colors.xml`. Второй список цветов разошёлся бы с
/// Android незаметно — так уже было в Python-версии.
///
/// Чего здесь нет по сравнению с macOS и почему:
/// - метрик шапки (`headerIcon`, `headerTrailing`, `headerBottom`): вертикаль
///   шапки на десктопе задаёт `HeaderMetrics` — это про светофор окна, которого
///   на телефоне нет вовсе. Шапку здесь рисует система, навигационной панелью;
/// - `sheetWidth`: лист на iOS всегда во всю ширину экрана, задавать её нечем и
///   незачем.
enum Style {

    /// Толщина разделительных линий.
    static let hairline: CGFloat = 1

    // MARK: Кнопка питания и статус

    /// Кнопка — единственный объёмный элемент экрана, поэтому она крупная.
    /// Сторона та же, что на macOS: кнопка — главное, что человек сравнивает,
    /// открыв телефон и ноутбук рядом.
    static let powerSide: CGFloat = 156
    /// Секунд на оборот бегущей дуги.
    static let powerSpin: Double = 1.4
    /// Доля окружности, которую занимает дуга.
    static let powerArc: Double = 100.0 / 360.0
    /// Насколько притушено кольцо-подложка под бегущей дугой.
    static let powerTrackOpacity: Double = 0.22

    /// Внутренняя кромка шайбы: отступ от кольца состояния в долях стороны.
    static let powerEdgeInset: CGFloat = 0.11
    /// Секунд на полный вдох-выдох кольца в простое.
    static let powerBreath: Double = 3.6
    /// До какой яркости кольцо притухает на выдохе.
    static let powerBreathLow: Double = 0.5
    /// Частота перерисовки «дыхания». Двадцать четыре кадра хватает для
    /// медленного затухания, а на телефоне лишние кадры — это ещё и батарея:
    /// экран с открытым приложением висит перед глазами минутами.
    static let powerBreathFPS: Double = 24

    /// Переход между состояниями подключения.
    ///
    /// Четверть секунды — столько, чтобы глаз успел заметить смену и не начал
    /// ждать. Дольше означало бы, что после нажатия кнопка ещё раздумывает,
    /// хотя расширение уже стартовало.
    static let stateChange: Animation = .easeInOut(duration: 0.25)

    /// Пустоты вокруг блока ужаты: кнопка крупная, и прежние отступы отдавали
    /// ей пол-экрана, оставляя списку три строки.
    static let powerBlockPadding: CGFloat = 14
    static let statusTop: CGFloat = 12
    static let substatusTop: CGFloat = 4
    static let substatusPadding: CGFloat = 20
    /// Между строкой подробностей и подписью режима.
    static let substatusLineGap: CGFloat = 4
    /// Высота фиксирована: подстатус меняется с одной строки на две, и без
    /// фиксации список серверов подпрыгивал бы при каждом переключении.
    static let substatusHeight: CGFloat = 34

    // MARK: Заголовок раздела

    /// Заголовок раздела встаёт ровно над именами серверов, а не над краем
    /// строки: колонка текста — самая заметная вертикаль в списке.
    static var sectionPadding: CGFloat { listPadding + rowMarker + rowTextLeading }
    static let sectionBottom: CGFloat = 8

    // MARK: Разрядка
    //
    // Разрядка тем шире, чем мельче и «служебнее» надпись: у знака и у
    // заголовков разделов она растягивает строку в полоску, а у крупного
    // статуса, наоборот, стягивает — иначе 26 pt рассыпаются на буквы.

    /// Заголовки разделов и подписи вроде «СЕРВЕРЫ».
    static let sectionTracking: CGFloat = 2
    /// Надпись SCVPN в шапке.
    static let wordmarkTracking: CGFloat = 4
    /// Крупная надпись состояния.
    static let statusTracking: CGFloat = -0.4

    // MARK: Список серверов

    /// Просвета между строками нет: их разделяет линия, а не пустота.
    static let listSpacing: CGFloat = 0
    /// Поле слева и справа от содержимого строки. Подсветка под нажатием при
    /// этом идёт от края до края — нажимается вся полоса, а не карточка.
    static let listPadding: CGFloat = 16
    static let listBottom: CGFloat = 10

    /// Без карточки и её внутренних полей строка стала ниже на 6.
    static let rowHeight: CGFloat = 52
    /// Ширина маркера выбранной строки.
    static let rowMarker: CGFloat = 2
    /// Насколько маркер короче строки сверху и снизу.
    static let rowMarkerInset: CGFloat = 13
    /// От маркера до текста.
    static let rowTextLeading: CGFloat = 12
    /// Между именем сервера и строкой с адресом.
    static let rowTextSpacing: CGFloat = 3
    /// Между текстом и пингом.
    static let rowGap: CGFloat = 8
    /// Ширина колонки пинга. Постоянная: иначе правый край значений гуляет от
    /// строки к строке и колонки не получается вовсе. Считана по самой длинной
    /// подписи — «нет ответа».
    ///
    /// Те же 72, что на macOS, хотя телефон уже. Даже на самом узком экране
    /// (320 pt) под имя и адрес остаётся 320 − 16·2 − 2 − 12 − 8 − 72 = 194 pt,
    /// а длинный адрес всё равно обрезается многоточием при любой ширине
    /// колонки. Сужать ради двух строк из ста смысла нет, а расхождение с
    /// десктопом было бы навсегда.
    static let pingColumn: CGFloat = 72

    static let stroke: CGFloat = 1

    // MARK: Листы поверх главного экрана

    /// Поля внутри листа. На macOS по бокам 18, потому что лист там — отдельное
    /// окно в 440 pt, ни к чему не прижатое. Здесь лист занимает весь экран, и
    /// его содержимое обязано стоять на той же вертикали, что список серверов
    /// под ним, — иначе текст прыгает вбок, стоит открыть лист.
    static let sheetPadding = EdgeInsets(top: 16, leading: 16, bottom: 16, trailing: 16)
    /// Между блоками внутри листа.
    static let sheetGap: CGFloat = 10
    /// Скругление вложенных панелей: поля ввода, списки, карточки подписок.
    /// Одно на всё — прежде соседние панели скруглялись на 10 и на 12.
    static let boxCorner: CGFloat = 8

    // MARK: Пустой список

    /// Между «что случилось» и «что делать».
    static let emptyGap: CGFloat = 8
    static let emptyPadding: CGFloat = 24

    // MARK: Лог

    /// Свёрнутая полоса с последней строкой.
    static let logStripHeight: CGFloat = 26
    /// Развёрнутый лог.
    static let logHeight: CGFloat = 130
    static let logPadding: CGFloat = 8
    static let logLineSpacing: CGFloat = 1
}

