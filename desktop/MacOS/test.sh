#!/bin/bash
# Проверки SCVPN для macOS.
#   ./test.sh            -> модульные проверки платформенного слоя
#   ./test.sh smoke      -> живая проверка (smoke_test.py): парсинг, конфиги, туннель
#   ./test.sh файл.py    -> запустить свой скрипт в окружении проекта
set -u
cd "$(dirname "$0")"

# venv живёт ВНЕ дерева репозитория, а не desktop/MacOS/venv. Причина —
# ~/Documents тут синхронизируется iCloud Drive, и синхронизация сама
# проставляет macOS-флаг UF_HIDDEN на файлы ВНУТРИ venv (не на всё дерево
# репозитория — замерено отдельно и точечно: снаружи venv, включая остальной
# репозиторий, флаг не появляется вовсе). Гонка идёт постоянно и по кругу:
# после чистки флаг возвращается за 75–90 секунд, не на всё дерево разом, а
# частями (917 файлов в одном заходе, 1081 в другом). Файлы, попавшие под
# флаг, Qt (QDir/QFactoryLoader) не видит — включая сами плагины платформы
# (libqcocoa.dylib и соседей), и QApplication падает qFatal ещё до создания
# окна. Внутри синхронизируемого дерева с этим бесполезно бороться разовой
# чисткой — переезд наружу, где синхронизации нет, решает вопрос раз и
# навсегда, а не откладывает его на следующий цикл синка.
#
# Переопределить путь: SCVPN_VENV=/путь/до/venv ./test.sh
VENV="${SCVPN_VENV:-$HOME/.venvs/scvpn}"
PY="$VENV/bin/python"

if [ ! -x "$PY" ]; then
  echo "[!] Нет venv. Создай: python3 -m venv \"$VENV\" && \"$VENV/bin/pip\" install -r requirements.txt"
  exit 1
fi

# Дешёвый пояс на случай, если venv всё же оказался под флагом (перенесли
# копированием с уже помеченного дерева, синхронизируемая родительская папка
# и т.п.). Один проход chflags не всегда добивает дерево целиком — тот же
# эффект частичного покрытия, что и у самой синхронизации, — поэтому гоняем
# несколько раз и проверяем результат находкой (-flags +hidden), а не
# считаем один вызов достаточным на слово.
for _ in 1 2 3; do
  remaining=$(find "$VENV" -flags +hidden 2>/dev/null | wc -l | tr -d ' ')
  [ "$remaining" = "0" ] && break
  chflags -R nohidden "$VENV" 2>/dev/null || true
done

case "${1:-}" in
  "")      "$PY" test_native.py ;;
  smoke)   "$PY" smoke_test.py ;;
  *)       "$PY" "$@" ;;
esac
