#pragma once

// Прототипы ядра Xray, объявленные у себя, а не взятые из его заголовка.
//
// Причина: LibXray.xcframework — статическая библиотека с модульной картой, и
// Xcode копирует её заголовки в общий каталог include. Там же оказывается
// модульная карта hev-socks5-tunnel, и сборка падает на «Multiple commands
// produce .../include/module.modulemap». Свои две строки вместо чужих
// заголовков снимают конфликт целиком: библиотека линкуется флагами, а её
// заголовки в сборку не попадают.
//
// Сигнатуры взяты из libXray/Headers/libXray.h релиза v26.7.28.

/// Единственная точка входа: JSON на вход, JSON на выход.
char *CGoInvoke(char *requestJSON);

/// Освободить строку, выделенную Go. Без этого течёт каждый вызов.
void CGoFree(char *value);
