import SCVPNCore

/// `Server` опознаётся списком по своему ключу.
///
/// Ключ — тот же, что лежит в `settings.json` как `selected_key`, поэтому
/// строка списка и выбранный сервер всегда говорят об одном и том же. Индекс
/// сюда не годится: подписка обновляется, и порядок меняется целиком.
extension Server: Identifiable {
    public var id: String { key() }
}
