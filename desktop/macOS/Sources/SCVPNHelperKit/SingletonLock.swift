import Foundation

/// Не пустить второй экземпляр демона поверх работающего.
///
/// launchd держит один экземпляр сам, но ничто не мешает запустить второй
/// руками поверх уже работающего launchd-демона. `killStaleSingbox` бьёт по
/// всей командной строке sing-box, не различая, чей это процесс, — второй демон
/// снёс бы **рабочий** туннель первого. А следом `daemonMain` отвязывает и
/// перехватывает сокет — так второй экземпляр забрал бы себе клиента первого,
/// который остался бы говорить в пустоту.
///
/// `flock` — ровно тот примитив, которым такие вещи принято решать в POSIX:
/// неблокирующий эксклюзивный захват до какой-либо разрушительной операции.
/// Замок на файле, а не на PID: PID-файлы врут после падения без очистки, а
/// `flock` снимается ядром сам, как только процесс, державший дескриптор,
/// умирает — второй демон встанет сразу же, без ручной уборки.
///
/// Дескриптор держится полем объекта, а объект обязан быть свойством демона:
/// попади дескриптор только в локальную переменную, ARC закрыл бы его вместе с
/// блокировкой, и второй демон спокойно встал бы следом за первым.
public final class SingletonLock {
    private let fd: Int32
    public let path: String

    public init(path: String) throws {
        self.path = path
        let fd = open(path, O_CREAT | O_RDWR, 0o600)
        guard fd >= 0 else {
            throw HelperPermissionError("не смог открыть файл замка \(path): \(String(cString: strerror(errno)))")
        }
        guard flock(fd, LOCK_EX | LOCK_NB) == 0 else {
            close(fd)
            throw HelperPermissionError("другой экземпляр демона уже работает (замок занят: \(path))")
        }
        self.fd = fd
    }

    deinit {
        // close снимает и flock — отдельного LOCK_UN не нужно.
        close(fd)
    }
}
