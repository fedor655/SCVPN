import SCVPNCore
import SwiftUI

/// Шрифты iOS-экрана. Цвета и знак — общие, из `SCVPNCore/UI/`; размеры и
/// отступы — рядом, в `Style+iOS.swift`.
///
/// **Источник истины — macOS:** `desktop/macOS/Sources/SCVPNApp/Views/Style.swift`.
/// Шкала обязана совпадать с тамошней размер в размер.
///
/// **Шкала строится на одном крупном размере.** Раньше всё лежало в вилке
/// 11–22 pt, и главная надпись экрана — состояние подключения — весила почти
/// столько же, сколько имя сервера в списке: глазу было не за что зацепиться.
/// Теперь состояние забирает 26 pt, а всё служебное уходит вниз, в 10–13 pt.
/// Промежуточных размеров нет намеренно: каждый лишний шаг шкалы снова
/// размывает разницу.
///
/// Прежнее «на телефоне надо покрупнее» здесь и было причиной расхождения с
/// десктопом: подписи подтягивали к главной надписи, пока разница между ними не
/// исчезла. Читаемость держится размером **главного**, а не общим укрупнением.
///
/// **Цифры везде табличные.** Аптайм тикает раз в секунду, пинг меняется на
/// каждом замере, и пропорциональные цифры дёргали разметку на каждом
/// обновлении: строка «00:11:59» шире, чем «00:12:00».
extension Font {
    /// Системный шрифт интерфейса: на iOS это SF.
    static func scvpnUI(_ size: CGFloat, weight: Font.Weight = .regular) -> Font {
        .system(size: size, weight: weight)
    }

    /// Моноширинный для логов. На macOS это Menlo; здесь системный
    /// моноширинный — он есть на любом телефоне и не тянет за собой шрифт,
    /// которого может не оказаться. Размеры те же.
    static func scvpnMono(_ size: CGFloat) -> Font {
        .system(size: size, design: .monospaced)
    }

    /// Надпись SCVPN в шапке: разрядка задаётся отдельно, через `.tracking`.
    ///
    /// Со своей разрядкой знак читается как метка экрана, а не как заголовок, и
    /// перестаёт спорить со строкой состояния.
    static var wordmark: Font { .system(size: 12, weight: .bold) }

    /// Состояние подключения — единственная крупная надпись на экране.
    static var statusBig: Font { .system(size: 26, weight: .semibold) }

    /// Строка под состоянием: аптайм и счётчики трафика, поэтому цифры
    /// табличные.
    static var substatus: Font { .system(size: 12).monospacedDigit() }

    static var section: Font { .system(size: 10, weight: .bold) }

    /// Имя сервера в списке. Полужирности хватает, чтобы имя отделилось от
    /// адреса под ним без увеличения размера.
    static var rowTitle: Font { .system(size: 13, weight: .medium) }

    /// Адрес под именем сервера.
    static var rowDetail: Font { .system(size: 11) }

    /// Значение пинга: те же 11 pt, но цифры табличные — колонка не пляшет при
    /// перезамере.
    static var rowPing: Font { .system(size: 11).monospacedDigit() }
}
